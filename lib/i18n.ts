const dictionaries: Record<Locale, Dict> = { en, fr };

export function t(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? en[key] ?? key;
}

/** Safe lookup for DB translations with [EN] fallback (plan Task 2.1 scenario). */
export function dbText(frValue: string | null | undefined, enValue: string, locale: Locale): string {
  if (locale === "fr" && !frValue) return `${enValue} [EN]`;
  return locale === "fr" ? (frValue as string) : enValue;
}
