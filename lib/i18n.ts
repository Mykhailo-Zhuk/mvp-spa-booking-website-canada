/** Pick the string for the active locale from three DB columns, EN as fallback. */
export function tri(en: string, fr: string, uk: string, locale: Locale): string {
  if (locale === "fr") return fr || en || "";
  if (locale === "uk") return uk || en || "";
  return en;
}

